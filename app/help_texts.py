_DEFAULT_HELP_TEMPLATE = "ℹ️ Справка по команде /{command} не найдена"


def get_command_help_text(command: str) -> str:
    """
    Возвращает детальный текст справки по команде.

    Если данные отсутствуют, возвращает стандартное уведомление.
    """
    normalized = command.lstrip("/").lower()
    help_entry = COMMAND_HELP.get(normalized)
    if help_entry:
        detailed = help_entry.get("detailed")
        if detailed:
            return detailed
    return _DEFAULT_HELP_TEMPLATE.format(command=normalized)